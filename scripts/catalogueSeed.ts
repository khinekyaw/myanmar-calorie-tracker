import type { Dish } from '@/data/dishes';
import { GENERIC_SOURCE, RECIPE_SOURCE } from '@/sync/mapping';

/**
 * SQL that loads the bundled dish list into the server `dishes` table
 * (supabase/seeds/catalogue.sql). Existing rows are left alone, so it is safe to run on
 * staging or production once: the nutritionist's edits are never overwritten.
 *
 * The numbers come from the recipe calculation (catalogue/, docs/CATALOGUE.md).
 * They are drafts, so no dish is marked verified here; the nutritionist sets
 * `verified_by` / `verified_at` in Studio once a recipe is reviewed.
 *
 * Regenerate after changing src/data/dishes.ts or running npm run catalogue:build:
 *   UPDATE_SEED=1 npx jest scripts/__tests__/catalogueSeed.test.ts
 */
export function catalogueSeedSql(list: Dish[]): string {
  const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
  const opt = (n: number | undefined) => (n === undefined ? 'null' : n);
  const arr = (xs: string[]) => (xs.length ? `array[${xs.map(q).join(', ')}]` : `'{}'::text[]`);
  const rows = [...list]
    .sort((a, b) => a.id.localeCompare(b.id))
    .map(
      (d) =>
        `  (${[
          q(d.id),
          q(d.name.my),
          q(d.name.en),
          arr(d.aliasesMy),
          arr(d.aliasesRoman),
          arr(d.addOns ?? []),
          q(d.unit),
          opt(d.servingG),
          d.kcal,
          d.carbG,
          d.proteinG,
          d.fatG,
          opt(d.sugarG),
          opt(d.sodiumMg),
          Boolean(d.oilSensitive),
          Boolean(d.hasSweetness),
          Boolean(d.isVegetarian),
          q(d.generic ? GENERIC_SOURCE : d.calculated ? RECIPE_SOURCE : 'illustrative placeholder'),
        ].join(', ')})`,
    );
  return `-- Generated by scripts/catalogueSeed.ts from src/data/dishes.ts. Do not edit by hand.
-- Dish catalogue: numbers from the recipe calculation (draft recipes), not verified.

insert into public.dishes (
  id, name_my, name_en, aliases_my, aliases_roman, add_ons, unit, serving_g,
  kcal, carb_g, protein_g, fat_g, sugar_g, sodium_mg, oil_sensitive, has_sweetness, is_vegetarian, source
) values
${rows.join(',\n')}
on conflict (id) do nothing;
`;
}

import type { Dish } from '@/mocks/dishes';

/**
 * SQL that loads the bundled dish list into the server `dishes` table
 * (supabase/seeds/catalogue.sql). Existing rows are left alone, so it is safe to run on
 * staging or production once: the nutritionist's edits are never overwritten.
 *
 * The numbers are ILLUSTRATIVE, so no dish is marked verified here; the
 * nutritionist sets `verified_by` / `verified_at` in Studio.
 *
 * Regenerate after changing src/mocks/dishes.ts:
 *   UPDATE_SEED=1 npx jest scripts/__tests__/catalogueSeed.test.ts
 */
export function catalogueSeedSql(list: Dish[]): string {
  const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
  const arr = (xs: string[]) => (xs.length ? `array[${xs.map(q).join(', ')}]` : `'{}'::text[]`);
  const rows = [...list]
    .sort((a, b) => a.id.localeCompare(b.id))
    .map(
      (d) =>
        `  (${[
          q(d.id),
          q(d.name.my),
          q(d.name.en),
          arr(d.aliasesMy),
          arr(d.aliasesRoman),
          q(d.unit),
          d.kcal,
          d.carbG,
          d.proteinG,
          d.fatG,
          Boolean(d.oilSensitive),
          Boolean(d.hasSweetness),
          Boolean(d.isVegetarian),
          q('illustrative placeholder'),
        ].join(', ')})`,
    );
  return `-- Generated by scripts/catalogueSeed.ts from src/mocks/dishes.ts. Do not edit by hand.
-- Dish catalogue: ILLUSTRATIVE numbers, not verified.

insert into public.dishes (
  id, name_my, name_en, aliases_my, aliases_roman, unit,
  kcal, carb_g, protein_g, fat_g, oil_sensitive, has_sweetness, is_vegetarian, source
) values
${rows.join(',\n')}
on conflict (id) do nothing;
`;
}
